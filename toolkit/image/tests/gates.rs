use primase_core::gate::{GateReport, Tolerance};
use primase_image::{
    Image, Samples, half, linear_to_srgb, mip_chain, pick_level, read_png, srgb_to_linear, write_png,
};
#[test]
fn png_independent_fixtures() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures");
    let mut gate = GateReport::new("synthetic PNG/Pillow and source samples", Tolerance::Exact);
    for name in [
        "c0d8", "c2d8", "c4d8", "c6d8", "c0d16", "c2d16", "c4d16", "c6d16", "L", "RGB", "P", "LA", "RGBA",
        "1",
    ] {
        let data = std::fs::read(root.join(format!("{name}.png"))).expect("png");
        let expected = std::fs::read(root.join(format!("{name}.rgba"))).expect("expected");
        let image = read_png(&data).expect("decode").image;
        let bytes = match &image.samples {
            Samples::U8(v) => v.clone(),
            Samples::U16(v) => v.iter().flat_map(|v| v.to_le_bytes()).collect(),
        };
        gate.compare_bytes(name, &bytes, &expected);
        let encoded = write_png(&image).expect("encode");
        assert_eq!(encoded, write_png(&image).expect("determinism"));
        assert_eq!(read_png(&encoded).expect("roundtrip").image, image);
    }
    println!("{gate}");
    gate.assert_passed();
}
/// Golden chains generated by the independent reference C# box filter.
#[test]
fn csharp_mip_chains() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures");
    let mut gate = GateReport::new("C# box filter mip levels", Tolerance::Exact);
    for name in [
        "mips1x1",
        "mips1x7",
        "mips7x1",
        "mips5x3",
        "mips7x9",
        "mips8x8",
        "mips17x15",
    ] {
        let b = std::fs::read(root.join(format!("{name}.bin"))).expect("fixture");
        let mut at = 0;
        let mut reference = Vec::new();
        while at < b.len() {
            let w = u32::from_le_bytes(b[at..at + 4].try_into().expect("w"));
            let h = u32::from_le_bytes(b[at + 4..at + 8].try_into().expect("h"));
            at += 8;
            let n = (w * h * 4) as usize;
            reference.push(Image {
                width: w,
                height: h,
                samples: Samples::U8(b[at..at + n].to_vec()),
            });
            at += n;
        }
        let chain = mip_chain(&reference[0]).expect("chain");
        assert_eq!(chain.len(), reference.len());
        for (i, (got, want)) in chain.iter().zip(&reference).enumerate() {
            assert_eq!((got.width, got.height), (want.width, want.height));
            let (Samples::U8(a), Samples::U8(b)) = (&got.samples, &want.samples) else {
                panic!("depth")
            };
            gate.compare_bytes(format!("{name}/{i}"), a, b);
        }
    }
    println!("{gate}");
    gate.assert_passed();
}
#[test]
fn color_and_selection() {
    assert_eq!(srgb_to_linear(0.), 0.);
    assert!((srgb_to_linear(1.) - 1.).abs() < 1e-15);
    assert!((srgb_to_linear(0.5) - 0.21404114048223255).abs() < 1e-15);
    assert!((linear_to_srgb(0.5) - 0.7353569830524495).abs() < 1e-15);
    assert_eq!(srgb_to_linear(0.04045), 0.04045 / 12.92);
    assert_eq!(linear_to_srgb(0.0031308), 0.0031308 * 12.92);
    for i in 0..256 {
        let x = i as f64 / 255.;
        assert!((linear_to_srgb(srgb_to_linear(x)) - x).abs() < 1e-14);
    }
    assert_eq!(pick_level(17, 9, 5, 4).expect("pick"), (2, 4, 2));
    assert_eq!(pick_level(17, 9, 2, 1).expect("smallest stored"), (1, 8, 4));
    assert!(pick_level(0, 9, 2, 1).is_err());
    assert!(pick_level(17, 9, 0, 1).is_err());
    assert!(pick_level(17, 9, 7, 1).is_err());
    let image = Image {
        width: 3,
        height: 1,
        samples: Samples::U16(vec![
            0, 0, 0, 65535, 30000, 30000, 30000, 65535, 60000, 60000, 60000, 65535,
        ]),
    };
    assert_eq!(
        half(&image).expect("u16 mean").samples,
        Samples::U16(vec![30000, 30000, 30000, 65535])
    );
}
#[test]
fn malformed_png() {
    assert!(read_png(include_bytes!("fixtures/bad_palette.png")).is_err());
    let data = include_bytes!("fixtures/P.png");
    for n in 0..data.len() {
        assert!(read_png(&data[..n]).is_err(), "prefix {n}");
    }
    let mut extra = data.to_vec();
    extra.push(0);
    assert!(read_png(&extra).is_err());
    let mut bad = data.to_vec();
    bad[29] ^= 1;
    assert!(read_png(&bad).is_err());
    assert!(
        write_png(&Image {
            width: 2,
            height: 2,
            samples: Samples::U8(vec![0; 4])
        })
        .is_err()
    );
}
