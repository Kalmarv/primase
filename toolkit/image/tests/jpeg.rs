#[test]
fn a_grey_file_decodes_to_grey_rgba_within_the_decoders_rounding_of_pillows_pixels() {
    let jpeg = read_jpeg(&GREY).unwrap();
    assert_eq!((jpeg.image.width, jpeg.image.height), (16, 16));
    assert_eq!(jpeg.color, JpegColor::Grey);
    assert!(!jpeg.progressive);
    assert!(jpeg.ignored.is_empty());
    let Samples::U8(px) = &jpeg.image.samples else {
        panic!("8-bit samples")
    };
    assert_eq!(px.len(), 16 * 16 * 4);
    for (i, texel) in px.as_chunks::<4>().0.iter().enumerate() {
        assert_eq!(texel[0], texel[1], "texel {i}: grey");
        assert_eq!(texel[1], texel[2], "texel {i}: grey");
        assert_eq!(texel[3], 255, "texel {i}: alpha");
        let want = i32::from(GREY_PILLOW[i]);
        assert!(
            (i32::from(texel[0]) - want).abs() <= 3,
            "texel {i}: {} against Pillow's {want}",
            texel[0]
        );
    }
}

#[test]
fn cmyk_what_is_not_a_jpeg_and_a_cut_file_are_errors() {
    let Err(Error::Jpeg(why)) = read_jpeg(&CMYK) else {
        panic!("a CMYK file is refused")
    };
    assert!(why.contains("CMYK"), "{why}");
    assert!(matches!(read_jpeg(b"not a jpeg"), Err(Error::Jpeg(_))));
    for cut in [30, 120, 300] {
        assert!(read_jpeg(&GREY[..cut]).is_err(), "cut at {cut}");
    }
}

#[test]
fn the_khronos_jpegs_decode_to_pillows_pixels() {
    let Some(root) = inputs::oracle(inputs::OracleSet::Khronos, inputs::Game::General, "sample-assets")
    else {
        return;
    };
    for (model, progressive, size) in [("MorphPrimitivesTest", false, 512), ("CesiumMan", true, 1024)] {
        let dir = root.join(model).join("images");
        let jpeg = std::fs::read(dir.join("0.jpg")).unwrap();
        let want = std::fs::read(dir.join("0.rgba")).unwrap();
        let decoded = read_jpeg(&jpeg).unwrap();
        assert_eq!(
            (decoded.image.width, decoded.image.height),
            (size, size),
            "{model}"
        );
        assert_eq!(decoded.color, JpegColor::YCbCr, "{model}");
        assert_eq!(decoded.progressive, progressive, "{model}");
        let Samples::U8(px) = &decoded.image.samples else {
            panic!("8-bit samples")
        };
        assert_eq!(px.len(), want.len(), "{model}");
        let mut worst = 0u8;
        let mut equal = 0usize;
        for (a, b) in px.iter().zip(&want) {
            worst = worst.max(a.abs_diff(*b));
            equal += usize::from(a == b);
        }
        let share = equal as f64 / px.len() as f64;
        println!("{model}: worst {worst}, {:.3}% equal", share * 100.0);
        assert!(worst <= 3, "{model}: worst difference {worst}");
        assert!(share >= 0.996, "{model}: {share} of the samples equal");
    }
}
