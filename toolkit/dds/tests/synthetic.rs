#![allow(clippy::unwrap_used)]
use primase_core::{
    ColorSpace, TexFormat, TexRole, Texture,
    gate::{GateReport, Tolerance},
};
use primase_dds::{from_dxgi, read, write_dx10, write_legacy};
fn texture(f: TexFormat, w: u32, h: u32, n: u32) -> Texture {
    Texture {
        width: w,
        height: h,
        format: f,
        levels: (0..n)
            .map(|i| {
                (0..f.level_size((w >> i).max(1), (h >> i).max(1)))
                    .map(|j| (j + i as usize * 17) as u8)
                    .collect()
            })
            .collect(),
        color_space: ColorSpace::Linear,
        role: TexRole::Other,
        normal: None,
    }
}
fn put(b: &mut [u8], o: usize, n: u32) {
    b[o..o + 4].copy_from_slice(&n.to_le_bytes());
}
/// Six synthetic oracle files generated by an independent C# reference writer.
#[test]
fn csharp_byte_identity() {
    let mut gate = GateReport::new("C# reference synthetic DDS", Tolerance::Exact);
    for (name, f, one, three) in [
        (
            "DXT1",
            TexFormat::Bc1,
            include_bytes!("fixtures/DXT1-1.dds").as_slice(),
            include_bytes!("fixtures/DXT1-3.dds").as_slice(),
        ),
        (
            "DXT3",
            TexFormat::Bc2,
            include_bytes!("fixtures/DXT3-1.dds").as_slice(),
            include_bytes!("fixtures/DXT3-3.dds").as_slice(),
        ),
        (
            "DXT5",
            TexFormat::Bc3,
            include_bytes!("fixtures/DXT5-1.dds").as_slice(),
            include_bytes!("fixtures/DXT5-3.dds").as_slice(),
        ),
    ] {
        for (n, expected) in [(1, one), (3, three)] {
            let t = texture(f, 16, 8, n);
            let actual = write_legacy(&t).unwrap();
            gate.compare_bytes(format!("{name}/{n}"), &actual, expected);
            assert_eq!(read(expected).unwrap(), t);
        }
    }
    eprintln!("{gate}");
    gate.assert_passed();
}
#[test]
fn dxgi_table_roundtrips_and_rejects_unknowns() {
    let mut gate = GateReport::new("typed DXGI roundtrips", Tolerance::Exact);
    for value in 0..=191 {
        if let Ok((f, c)) = from_dxgi(value) {
            for (w, h, n) in [(1, 1, 1), (7, 5, 3), (16, 8, 5)] {
                let mut t = texture(f, w, h, n);
                t.color_space = c;
                let b = write_dx10(&t).unwrap();
                assert_eq!(u32::from_le_bytes(b[128..132].try_into().unwrap()), value);
                assert_eq!(read(&b).unwrap(), t);
                gate.record(format!("{value}/{w}/{h}"), 0.0);
            }
        }
    }
    for v in [0, 1, 27, 70, 73, 76, 79, 82, 94, 97, 999] {
        assert!(from_dxgi(v).is_err());
    }
    assert!(primase_dds::to_dxgi(TexFormat::Bc5Unorm, ColorSpace::Srgb).is_err());
    eprintln!("{gate}");
    gate.assert_passed();
}
#[test]
fn legacy_aliases_and_masks() {
    use TexFormat::*;
    for (four, f) in [
        (b"DXT1", Bc1),
        (b"DXT3", Bc2),
        (b"DXT5", Bc3),
        (b"ATI1", Bc4Unorm),
        (b"BC4U", Bc4Unorm),
        (b"BC4S", Bc4Snorm),
        (b"ATI2", Bc5Unorm),
        (b"BC5U", Bc5Unorm),
        (b"BC5S", Bc5Snorm),
    ] {
        let t = texture(f, 4, 4, 1);
        let mut b = write_dx10(&t).unwrap();
        b.drain(128..148);
        b[84..88].copy_from_slice(four);
        assert_eq!(read(&b).unwrap(), t);
    }
    for (flags, masks, f) in [
        (0x40, [16, 0xf800, 0x7e0, 0x1f, 0], B5g6r5Unorm),
        (0x41, [16, 0x7c00, 0x3e0, 0x1f, 0x8000], B5g5r5a1Unorm),
        (0x41, [16, 0xf00, 0xf0, 0xf, 0xf000], B4g4r4a4Unorm),
        (0x41, [32, 0xff, 0xff00, 0xff0000, 0xff000000], Rgba8Unorm),
        (0x41, [32, 0xff0000, 0xff00, 0xff, 0xff000000], Bgra8Unorm),
        (0x40, [32, 0xff0000, 0xff00, 0xff, 0], Bgrx8Unorm),
        (0x41, [32, 0x3ff, 0xffc00, 0x3ff00000, 0xc0000000], Rgb10a2Unorm),
        (0x20000, [8, 0xff, 0, 0, 0], R8Unorm),
        (0x20000, [16, 0xffff, 0, 0, 0], R16Unorm),
        (0x20001, [16, 0xff, 0, 0, 0xff00], Rg8Unorm),
        (2, [8, 0, 0, 0, 0xff], A8Unorm),
    ] {
        let t = texture(f, 7, 5, 3);
        let mut b = write_dx10(&t).unwrap();
        b.drain(128..148);
        put(&mut b, 80, flags);
        put(&mut b, 84, 0);
        for (i, v) in masks.into_iter().enumerate() {
            put(&mut b, 88 + i * 4, v);
        }
        assert_eq!(read(&b).unwrap(), t);
        put(&mut b, 92, 0x12345678);
        assert!(read(&b).is_err());
    }
}
#[test]
fn malformed_inputs_and_unsupported_shapes() {
    let good = write_dx10(&texture(TexFormat::Bc1, 7, 5, 3)).unwrap();
    for end in 0..good.len() {
        assert!(read(&good[..end]).is_err(), "prefix {end}");
    }
    for (offset, value, detail) in [
        (4, 123, "header size"),
        (76, 31, "header size"),
        (8, 0, "flags"),
        (12, 0, "zero"),
        (28, 99, "mip count"),
        (112, 0x200, "cube"),
        (112, 0x400, "cube"),
        (24, 2, "volume"),
        (132, 4, "dimension"),
        (132, 2, "dimension"),
        (136, 4, "cube"),
        (140, 0, "array"),
        (140, 2, "array"),
        (144, 2, "alpha"),
        (128, 70, "DXGI"),
        (20, 1, "linear size"),
    ] {
        let mut b = good.clone();
        put(&mut b, offset, value);
        let e = read(&b).unwrap_err().to_string();
        assert!(e.contains(detail), "{offset}: {e}");
    }
    let mut trailing = good.clone();
    trailing.push(0);
    assert!(read(&trailing).unwrap_err().to_string().contains("trailing"));
    let mut t = texture(TexFormat::Bc1, 4, 4, 1);
    t.levels[0].pop();
    assert!(write_legacy(&t).is_err());
    t.levels.clear();
    assert!(write_dx10(&t).is_err());
    let mut pitched = write_dx10(&texture(TexFormat::R8Unorm, 3, 2, 1)).unwrap();
    put(&mut pitched, 20, 4);
    assert!(read(&pitched).unwrap_err().to_string().contains("pitch"));
    let mut huge = good;
    put(&mut huge, 16, u32::MAX);
    put(&mut huge, 12, u32::MAX);
    put(&mut huge, 128, 2);
    put(&mut huge, 8, 0x1007);
    assert!(read(&huge).is_err());
}

/// Hand-built headers from the documented DDS structures, independent of Rust serialization.
#[test]
fn independent_dx10_and_mask_fixtures() {
    let t = read(include_bytes!("fixtures/dx10-bc7-srgb.dds")).unwrap();
    assert_eq!(
        (t.width, t.height, t.format, t.color_space),
        (4, 4, TexFormat::Bc7, ColorSpace::Srgb)
    );
    assert_eq!(t.levels, vec![(0..16).collect::<Vec<u8>>()]);
    assert_eq!(
        write_dx10(&t).unwrap(),
        include_bytes!("fixtures/dx10-bc7-srgb.dds")
    );
    let t = read(include_bytes!("fixtures/legacy-a8.dds")).unwrap();
    assert_eq!((t.width, t.height, t.format), (2, 1, TexFormat::A8Unorm));
    assert_eq!(t.levels, vec![vec![0, 255]]);
}
