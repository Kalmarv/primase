#[test]
fn dxgi_table_roundtrips_and_rejects_unknowns() {
    let mut gate = GateReport::new("typed DXGI roundtrips", Tolerance::Exact);
    // Both directions against the specification values, so an empty or partly wrong table fails.
    for &(value, f, c) in DXGI_KNOWN {
        assert_eq!(from_dxgi(value).unwrap(), (f, c), "DXGI {value}");
        assert_eq!(primase_dds::to_dxgi(f, c).unwrap(), value, "{f:?} {c:?}");
        for (w, h, n) in [(1, 1, 1), (7, 5, 3), (16, 8, 5)] {
            let mut t = texture(f, w, h, n);
            t.color_space = c;
            let b = write_dx10(&t).unwrap();
            assert_eq!(u32::from_le_bytes(b[128..132].try_into().unwrap()), value);
            assert_eq!(read(&b).unwrap(), t);
            gate.record(format!("{value}/{w}/{h}"), 0.0);
        }
    }
    // Every value in the table's range maps exactly when the specification says it does.
    for value in 0..=191u32 {
        assert_eq!(
            from_dxgi(value).is_ok(),
            DXGI_KNOWN.iter().any(|&(v, _, _)| v == value),
            "DXGI {value}"
        );
    }
    for v in [0, 1, 27, 70, 73, 76, 79, 82, 94, 97, 999] {
        assert!(from_dxgi(v).is_err());
    }
    assert!(primase_dds::to_dxgi(TexFormat::Bc5Unorm, ColorSpace::Srgb).is_err());
    assert_eq!(gate.checked, DXGI_KNOWN.len() as u64 * 3);
    eprintln!("{gate}");
    gate.assert_passed();
}
/// A legacy-header file of `t` with the given pixel format (flags, FourCC, bit count, R G B A masks).
fn legacy(t: &Texture, flags: u32, fourcc: &[u8; 4], bits: u32, masks: [u32; 4]) -> Vec<u8> {
    let mut b = write_dx10(t).unwrap();
    b.drain(128..148);
    put(&mut b, 80, flags);
    b[84..88].copy_from_slice(fourcc);
    put(&mut b, 88, bits);
    for (i, v) in masks.into_iter().enumerate() {
        put(&mut b, 92 + i * 4, v);
    }
    b
}

/// DirectXTex's legacy table (`g_LegacyDDSMap`), entry by entry: what reads verbatim, and what DirectXTex converts as
/// it loads, which is refused rather than misread.
#[test]
fn legacy_aliases_and_masks() {
    use TexFormat::*;
    let mut fourccs: Vec<([u8; 4], TexFormat)> = vec![
        (*b"DXT1", Bc1),
        (*b"DXT3", Bc2),
        (*b"DXT5", Bc3),
        (*b"BC4U", Bc4Unorm),
        (*b"ATI1", Bc4Unorm),
        (*b"BC4S", Bc4Snorm),
        (*b"BC5U", Bc5Unorm),
        (*b"ATI2", Bc5Unorm),
        (*b"A2XY", Bc5Unorm),
        (*b"BC5S", Bc5Snorm),
        (*b"BC6H", Bc6hUfloat),
        (*b"BC7L", Bc7),
        (*b"BC7\0", Bc7),
    ];
    // DXT5 with swizzled channels reads as the BC3 blocks it is.
    for code in [
        b"A2D5", b"xGBR", b"RxBG", b"RBxG", b"xRBG", b"RGxB", b"xGxR", b"GXRB", b"GRXB", b"RXGB", b"BRGX",
    ] {
        fourccs.push((*code, Bc3));
    }
    // D3DFMT values as FourCCs (D3DX's float and 16-bit formats).
    for (value, f) in [
        (36_u32, Rgba16Unorm),
        (111, R16Float),
        (112, Rg16Float),
        (113, Rgba16Float),
        (114, R32Float),
        (115, Rg32Float),
        (116, Rgba32Float),
    ] {
        fourccs.push((value.to_le_bytes(), f));
    }
    for (code, f) in fourccs {
        let t = texture(f, 7, 5, 3);
        assert_eq!(read(&legacy(&t, 4, &code, 0, [0; 4])).unwrap(), t, "{code:?}");
    }
    for (code, f) in [(b"DXT2", Bc2), (b"DXT4", Bc3)] {
        let b = legacy(&texture(f, 4, 4, 1), 4, code, 0, [0; 4]);
        let p = parse(&b).unwrap();
        assert_eq!((p.dds.format, p.dds.alpha_mode), (f, AlphaMode::Premultiplied));
        assert!(read(&b).unwrap_err().to_string().contains("premultiplied"));
        assert_eq!(write(&p.dds, WriteHeader::Auto).unwrap(), b);
    }
    for code in [
        b"RGBG",
        b"GRGB",
        b"YUY2",
        b"UYVY",
        &110_u32.to_le_bytes(),
        b"ETC1",
        b"DX9 ",
    ] {
        let e = read(&legacy(&texture(Bc1, 4, 4, 1), 4, code, 0, [0; 4])).unwrap_err();
        assert!(matches!(e, Error::Unsupported(_)), "{code:?}: {e}");
    }

    // Masks, and the offset of a mask the entry's kind compares (alpha: A; luminance and bump: R; RGB(A): any).
    for (flags, bits, masks, f, compared) in [
        (0x41, 32, [0xff0000, 0xff00, 0xff, 0xff000000], Bgra8Unorm, 92),
        (0x40, 32, [0xff0000, 0xff00, 0xff, 0], Bgrx8Unorm, 100),
        (0x41, 32, [0xff, 0xff00, 0xff0000, 0xff000000], Rgba8Unorm, 104),
        (0x40, 32, [0xffff, 0xffff0000, 0, 0], Rg16Unorm, 96),
        (
            0x41,
            32,
            [0x3ff00000, 0xffc00, 0x3ff, 0xc0000000],
            Rgb10a2Unorm,
            92,
        ),
        (0x40, 16, [0xf800, 0x7e0, 0x1f, 0], B5g6r5Unorm, 92),
        (0x41, 16, [0x7c00, 0x3e0, 0x1f, 0x8000], B5g5r5a1Unorm, 104),
        (0x41, 16, [0xf00, 0xf0, 0xf, 0xf000], B4g4r4a4Unorm, 96),
        (0x20000, 8, [0xff, 0, 0, 0], R8Unorm, 92),
        (0x20000, 16, [0xffff, 0, 0, 0], R16Unorm, 92),
        (0x20001, 16, [0xff, 0, 0, 0xff00], Rg8Unorm, 104),
        (0x20001, 8, [0xff, 0, 0, 0xff00], Rg8Unorm, 92),
        (0x40, 8, [0xff, 0, 0, 0], R8Unorm, 92),
        (0x40, 16, [0xffff, 0, 0, 0], R16Unorm, 96),
        (0x41, 16, [0xff, 0, 0, 0xff00], Rg8Unorm, 104),
        (2, 8, [0, 0, 0, 0xff], A8Unorm, 104),
        (0x40, 32, [0xffffffff, 0, 0, 0], R32Float, 92),
        (0x80000, 16, [0xff, 0xff00, 0, 0], Rg8Snorm, 92),
        (0x80000, 32, [0xff, 0xff00, 0xff0000, 0xff000000], Rgba8Snorm, 92),
        (0x80000, 32, [0xffff, 0xffff0000, 0, 0], Rg16Snorm, 92),
    ] {
        let t = texture(f, 7, 5, 3);
        let mut b = legacy(&t, flags, &[0; 4], bits, masks);
        assert_eq!(read(&b).unwrap(), t, "{f:?} {flags:#x} {bits}");
        put(&mut b, compared, 0x12345678);
        assert!(read(&b).is_err(), "{f:?}: mask at {compared}");
        let mut b = legacy(&t, flags, &[0; 4], bits, masks);
        put(&mut b, 88, 24);
        assert!(read(&b).is_err(), "{f:?}: bit count");
    }
    // DirectXTex compares only the masks an entry's kind uses: luminance reads R alone.
    let t = texture(R8Unorm, 4, 4, 1);
    assert_eq!(
        read(&legacy(&t, 0x20000, &[0; 4], 8, [0xff, 0x1234, 7, 0])).unwrap(),
        t
    );

    // Formats DirectXTex converts as it loads (swizzle, forced alpha, expansion, palettes): refused by name.
    for (flags, bits, masks, name) in [
        (0x41, 32, [0x3ff, 0xffc00, 0x3ff00000, 0xc0000000], "A2R10G10B10"),
        (0x40, 32, [0xff, 0xff00, 0xff0000, 0], "X8B8G8R8"),
        (0x40, 24, [0xff0000, 0xff00, 0xff, 0], "R8G8B8"),
        (0x40, 16, [0x7c00, 0x3e0, 0x1f, 0], "X1R5G5B5"),
        (0x41, 16, [0xe0, 0x1c, 0x3, 0xff00], "A8R3G3B2"),
        (0x40, 8, [0xe0, 0x1c, 0x3, 0], "R3G3B2"),
        (0x40, 16, [0xf00, 0xf0, 0xf, 0], "X4R4G4B4"),
        (0x20001, 8, [0xf, 0, 0, 0xf0], "A4L4"),
        (0x20, 8, [0; 4], "P8"),
        (0x21, 16, [0, 0, 0, 0xff00], "A8P8"),
        (0x40000, 16, [0x1f, 0x3e0, 0xfc00, 0], "L6V5U5"),
        (0x40000, 32, [0xff, 0xff00, 0xff0000, 0], "X8L8V8U8"),
        (
            0x80001,
            32,
            [0x3ff00000, 0xffc00, 0x3ff, 0xc0000000],
            "A2W10V10U10",
        ),
    ] {
        let e = read(&legacy(&texture(R8Unorm, 4, 4, 1), flags, &[0; 4], bits, masks)).unwrap_err();
        assert!(e.to_string().contains(name), "{name}: {e}");
    }

    // NVIDIA Texture Tools: with its marker, its sRGB and normal-map flags are ignored for the match and the first
    // gives the sRGB view where the format has one; without the marker they are unknown flags.
    let t = texture(Rgba8Unorm, 4, 4, 1);
    let rgba = [0xff, 0xff00, 0xff0000, 0xff000000];
    let mut b = legacy(&t, 0xc000_0041, &[0; 4], 32, rgba);
    assert!(read(&b).is_err());
    b[68..72].copy_from_slice(b"NVTT");
    let mut srgb = t.clone();
    srgb.color_space = ColorSpace::Srgb;
    assert_eq!(read(&b).unwrap(), srgb);
    put(&mut b, 80, 0x8000_0041);
    assert_eq!(read(&b).unwrap(), t);
    let r8 = texture(R8Unorm, 4, 4, 1);
    let mut b = legacy(&r8, 0x4002_0000, &[0; 4], 8, [0xff, 0, 0, 0]);
    b[68..72].copy_from_slice(b"NVTT");
    assert_eq!(read(&b).unwrap(), r8, "R8 has no sRGB view");

    // The FourCC flag beside the RGB flag (0x44, as some writers set both): a FourCC states the format and the masks
    // are not read; a zero FourCC leaves the masks to say (an Elden Ring layer texture's header: BGRX masks), where
    // DirectXTex refuses the file.
    let t = texture(Bc1, 4, 4, 1);
    assert_eq!(
        read(&legacy(&t, 0x44, b"DXT1", 32, [0xff0000, 0, 0, 0])).unwrap(),
        t
    );
    let t = texture(Bgrx8Unorm, 7, 5, 3);
    assert_eq!(
        read(&legacy(&t, 0x44, &[0; 4], 32, [0xff0000, 0xff00, 0xff, 0])).unwrap(),
        t
    );
}

#[test]
fn malformed_inputs_and_unsupported_shapes() {
    let good = write_dx10(&texture(TexFormat::Bc1, 7, 5, 3)).unwrap();
    for end in 0..good.len() {
        assert!(read(&good[..end]).is_err(), "prefix {end}");
    }
    for (offset, value, detail) in [
        (4, 123, "header size"),
        (76, 31, "pixel format size"),
        (12, 0, "pixels"),
        (28, 99, "mip levels"),
        (132, 4, "DDSD_DEPTH"),
        (132, 2, "1D texture with height"),
        (132, 5, "resource dimension"),
        (136, 4, "truncated"),
        (136, 2, "misc flags"),
        (140, 2, "truncated"),
        (144, 2, "premultiplied"),
        (144, 5, "miscFlags2"),
        (128, 70, "DXGI"),
    ] {
        let mut b = good.clone();
        put(&mut b, offset, value);
        let e = read(&b).unwrap_err().to_string();
        assert!(e.contains(detail), "{offset}: {e}");
    }
    // Fields DirectXTex doesn't read decide nothing here either: the header flags, a 2D texture's depth, the pitch or
    // linear size, cube bits in caps2 under a DX10 header, and an arraySize of 0 (read as 1).
    for (offset, value) in [(8, 0), (24, 9), (20, 1), (112, 0x200), (140, 0)] {
        let mut b = good.clone();
        put(&mut b, offset, value);
        assert_eq!(read(&b).unwrap(), read(&good).unwrap(), "{offset}");
    }
    let mut trailing = good.clone();
    trailing.push(0);
    assert!(read(&trailing).unwrap_err().to_string().contains("trailing"));
    // Padded rows (a 3-texel R8 row padded to 4) are a longer payload than the layout's.
    let mut padded = write_dx10(&texture(TexFormat::R8Unorm, 3, 2, 1)).unwrap();
    padded.extend([0, 0]);
    assert!(read(&padded).unwrap_err().to_string().contains("trailing"));
    // A legacy cube must name all six faces.
    let mut cube = write(&cube_dds(TexFormat::Bc1, 1, 1), WriteHeader::Auto).unwrap();
    put(&mut cube, 112, 0x600);
    assert!(read_layers(&cube).unwrap_err().to_string().contains("six faces"));
    let mut t = texture(TexFormat::Bc1, 4, 4, 1);
    t.levels[0].pop();
    assert!(write_legacy(&t).is_err());
    t.levels.clear();
    assert!(write_dx10(&t).is_err());
    let mut huge = good;
    put(&mut huge, 16, u32::MAX);
    put(&mut huge, 12, u32::MAX);
    put(&mut huge, 128, 2);
    put(&mut huge, 140, u32::MAX);
    assert!(read(&huge).is_err());
}

/// Hand-built headers from the documented DDS structures, independent of Rust serialization.
#[test]
fn independent_dx10_and_mask_fixtures() {
    let fixture = include_bytes!("fixtures/dx10-bc7-srgb.dds");
    let t = read(fixture).unwrap();
    assert_eq!(
        (t.width, t.height, t.format, t.color_space),
        (4, 4, TexFormat::Bc7, ColorSpace::Srgb)
    );
    assert_eq!(t.levels, vec![(0..16).collect::<Vec<u8>>()]);
    // The fixture leaves DDSD_MIPMAPCOUNT out of a single-level file and the depth of a 2D texture 0; DirectXTex (and so
    // this writer) always sets the flag and writes a depth of 1.
    let mut canonical = fixture.to_vec();
    put(&mut canonical, 8, 0xa1007);
    put(&mut canonical, 24, 1);
    assert_eq!(write_dx10(&t).unwrap(), canonical);
    let t = read(include_bytes!("fixtures/legacy-a8.dds")).unwrap();
    assert_eq!((t.width, t.height, t.format), (2, 1, TexFormat::A8Unorm));
    assert_eq!(t.levels, vec![vec![0, 255]]);
}

/// A resource of any shape whose every image is distinct: byte `j` of image `i` of level `l` is `j + 7 i + 61 l`.
fn dds(shape: Shape, format: TexFormat, width: u32, height: u32, mips: u32) -> Dds {
    Dds {
        shape,
        width,
        height,
        format,
        color_space: ColorSpace::Linear,
        alpha_mode: AlphaMode::Unknown,
        levels: (0..mips)
            .map(|l| {
                let size = format.level_size((width >> l).max(1), (height >> l).max(1));
                (0..shape.images_at(l))
                    .map(|i| {
                        (0..size)
                            .map(|j| (j as u64 + 7 * i + 61 * u64::from(l)) as u8)
                            .collect()
                    })
                    .collect()
            })
            .collect(),
    }
}
fn cube_dds(format: TexFormat, cubes: u32, mips: u32) -> Dds {
    dds(Shape::Cube { cubes }, format, 8, 8, mips)
}

/// Every shape in every header that can hold it reads back as written, in the file order DDS uses: 1D, 2D and cube
/// items each with all their mips, volumes level by level.
#[test]
fn every_shape_round_trips_in_every_header() {
    use TexFormat::*;
    let mut gate = GateReport::new("shape x format x header round trips", Tolerance::Exact);
    for format in [Rgba8Unorm, Bc1, Bc7, R16Float, B5g6r5Unorm] {
        for (shape, w, h, mips) in [
            (Shape::D1 { layers: 1 }, 16, 1, 5),
            (Shape::D1 { layers: 3 }, 9, 1, 2),
            (Shape::D2 { layers: 1 }, 13, 7, 4),
            (Shape::D2 { layers: 4 }, 16, 8, 5),
            (Shape::Cube { cubes: 1 }, 8, 8, 4),
            (Shape::Cube { cubes: 3 }, 4, 4, 1),
            (Shape::D3 { depth: 5 }, 8, 4, 4),
            (Shape::D3 { depth: 1 }, 2, 2, 2),
        ] {
            let d = dds(shape, format, w, h, mips);
            for header in [WriteHeader::Auto, WriteHeader::Legacy, WriteHeader::Dx10] {
                let item = format!("{format:?} {shape:?} {header:?}");
                let one = !matches!(
                    shape,
                    Shape::D1 { layers: 2.. } | Shape::D2 { layers: 2.. } | Shape::Cube { cubes: 2.. }
                );
                let has_legacy = format != Bc7;
                let bytes = match write(&d, header) {
                    Ok(b) => b,
                    Err(e) => {
                        assert!(
                            header == WriteHeader::Legacy && !(one && has_legacy),
                            "{item}: {e}"
                        );
                        continue;
                    }
                };
                let p = parse(&bytes).unwrap();
                let legacy_header = matches!(p.header, HeaderKind::Legacy(_));
                let expect_legacy = match header {
                    WriteHeader::Legacy => true,
                    WriteHeader::Dx10 => false,
                    WriteHeader::Auto => one && has_legacy && !matches!(shape, Shape::D1 { .. }),
                };
                assert_eq!(legacy_header, expect_legacy, "{item}");
                let mut expected = d.clone();
                if let (true, Shape::D1 { layers }) = (legacy_header, shape) {
                    // A legacy header has no 1D textures: it reads back as 2D of height 1, as in DirectXTex.
                    expected.shape = Shape::D2 { layers };
                }
                assert_eq!(p.dds, expected, "{item}");
                let order: Vec<u8> = match shape {
                    Shape::D3 { .. } => d.levels.iter().flatten().flatten().copied().collect(),
                    _ => (0..d.levels[0].len())
                        .flat_map(|i| d.levels.iter().flat_map(move |l| l[i].iter().copied()))
                        .collect(),
                };
                let start = if legacy_header { 128 } else { 148 };
                gate.compare_bytes(item, &bytes[start..], &order);
            }
        }
    }
    eprintln!("{gate}");
    gate.assert_passed();
}

/// A DX10 cube whose arraySize counts faces (6 per cube), as FromSoftware's environment cubes are written: read as
/// DirectXTex's permissive load reads it, when the payload is exactly the smaller count's.
#[test]
fn face_counted_cubes() {
    for cubes in [1, 2] {
        let d = cube_dds(TexFormat::Rgba8Unorm, cubes, 3);
        let mut bytes = write(&d, WriteHeader::Dx10).unwrap();
        let p = parse(&bytes).unwrap();
        assert!(!p.faces_counted);
        put(&mut bytes, 140, cubes * 6);
        let p = parse(&bytes).unwrap();
        assert!(p.faces_counted);
        assert_eq!(p.dds, d);
        assert!(parse(&bytes[..bytes.len() - 1]).is_err());
        let mut longer = bytes.clone();
        longer.push(0);
        assert!(parse(&longer).is_err());
    }
    // Six cubes stored as six: the stated count fits, so it is read as stated.
    let d = cube_dds(TexFormat::Bc1, 6, 1);
    let p = parse(&write(&d, WriteHeader::Auto).unwrap()).unwrap();
    assert_eq!((p.dds.shape, p.faces_counted), (Shape::Cube { cubes: 6 }, false));
    // A count that isn't a multiple of six, or a payload that fits neither count, is refused.
    let mut bytes = write(&cube_dds(TexFormat::Bc1, 1, 1), WriteHeader::Dx10).unwrap();
    put(&mut bytes, 140, 2);
    assert!(parse(&bytes).unwrap_err().to_string().contains("truncated"));
    put(&mut bytes, 140, 12);
    assert!(parse(&bytes).is_err());
}

#[test]
fn header_choices_keep_or_drop_what_they_say() {
    use TexFormat::*;
    let bytes_of = |d: &Dds, h| write(d, h).unwrap();
    // Auto keeps an alpha mode: DXT2/DXT4 for premultiplied BC2/BC3, else the DX10 header with miscFlags2.
    let mut d = dds(Shape::D2 { layers: 1 }, Bc3, 8, 8, 1);
    d.alpha_mode = AlphaMode::Premultiplied;
    assert_eq!(&bytes_of(&d, WriteHeader::Auto)[84..88], b"DXT4");
    for (format, alpha) in [
        (Rgba8Unorm, AlphaMode::Straight),
        (Bc7, AlphaMode::Premultiplied),
        (Bc1, AlphaMode::Opaque),
    ] {
        let mut d = dds(Shape::D2 { layers: 1 }, format, 8, 8, 1);
        d.alpha_mode = alpha;
        let b = bytes_of(&d, WriteHeader::Auto);
        assert_eq!(
            (&b[84..88], u32::from(b[144])),
            (&b"DX10"[..], alpha.misc2()),
            "{format:?}"
        );
        assert_eq!(parse(&b).unwrap().dds, d);
    }
    // Legacy is texconv -dx9: the colour space and alpha mode are dropped where the pixel format can't say them.
    let mut d = dds(Shape::D2 { layers: 1 }, Bc1, 8, 8, 1);
    d.color_space = ColorSpace::Srgb;
    d.alpha_mode = AlphaMode::Straight;
    let p = parse(&bytes_of(&d, WriteHeader::Legacy)).unwrap();
    assert_eq!(
        (p.dds.color_space, p.dds.alpha_mode),
        (ColorSpace::Linear, AlphaMode::Unknown)
    );
    // sRGB has no legacy pixel format without -dx9: Auto writes DX10.
    assert!(matches!(
        parse(&bytes_of(&d, WriteHeader::Auto)).unwrap().header,
        HeaderKind::Dx10
    ));
    for (format, legacy, dx9) in [(Bc4Unorm, b"BC4U", b"ATI1"), (Bc5Unorm, b"BC5U", b"ATI2")] {
        let d = dds(Shape::D2 { layers: 1 }, format, 8, 8, 1);
        assert_eq!(&bytes_of(&d, WriteHeader::Auto)[84..88], legacy);
        assert_eq!(&bytes_of(&d, WriteHeader::Legacy)[84..88], dx9);
    }
    // 10:10:10:2 is legacy only under -dx9, with the masks D3DX wrote (red in the high bits).
    let d = dds(Shape::D2 { layers: 1 }, Rgb10a2Unorm, 4, 4, 1);
    assert!(matches!(
        parse(&bytes_of(&d, WriteHeader::Auto)).unwrap().header,
        HeaderKind::Dx10
    ));
    let b = bytes_of(&d, WriteHeader::Legacy);
    assert_eq!(u32::from_le_bytes(b[92..96].try_into().unwrap()), 0x3ff00000);
    assert_eq!(parse(&b).unwrap().dds, d);
}

#[test]
fn core_conversions() {
    use TexFormat::*;
    let cube = write(&cube_dds(Bc1, 1, 2), WriteHeader::Auto).unwrap();
    assert!(read(&cube).unwrap_err().to_string().contains("read it as layers"));
    let layers = read_layers(&cube).unwrap();
    assert_eq!(layers.shape, TextureShape::Cube { cubes: 1 });
    assert_eq!(write_layers(&layers, WriteHeader::Auto).unwrap(), cube);
    let t = texture(Rgba8Unorm, 13, 7, 3);
    let flat = read_layers(&write_dx10(&t).unwrap()).unwrap();
    assert_eq!(flat.shape, TextureShape::Array { layers: 1 });
    assert_eq!(flat.levels.concat(), t.levels);
    // A 1D texture is a height-1 image to core, which has no 1D shape.
    let line = write(
        &dds(Shape::D1 { layers: 1 }, R16Float, 16, 1, 5),
        WriteHeader::Auto,
    )
    .unwrap();
    assert_eq!(read(&line).unwrap().height, 1);
    let lines = write(
        &dds(Shape::D1 { layers: 2 }, R16Float, 16, 1, 1),
        WriteHeader::Auto,
    )
    .unwrap();
    assert_eq!(
        read_layers(&lines).unwrap().shape,
        TextureShape::Array { layers: 2 }
    );
    let volume = write(&dds(Shape::D3 { depth: 4 }, R8Unorm, 4, 4, 3), WriteHeader::Auto).unwrap();
    let v = read_layers(&volume).unwrap();
    assert_eq!(v.shape, TextureShape::Volume { depth: 4 });
    assert_eq!(v.levels.iter().map(Vec::len).collect::<Vec<_>>(), [4, 2, 1]);
    assert_eq!(write_layers(&v, WriteHeader::Auto).unwrap(), volume);
}
