/// The effect name of a stored effect name hash (the joaat of the lowercase name).
pub fn effect(hash: u32) -> Option<&'static str> {
    EFFECTS
        .iter()
        .copied()
        .find(|n| primase_foundations::hash::joaat(n.as_bytes()) == hash)
}

/// The hash a listed name stands for: its joaat, or for a `hash_XXXXXXXX` entry (a parameter the list knows only by
/// its hash) that hash.
fn hash_of(name: &str) -> u32 {
    match name
        .strip_prefix("hash_")
        .and_then(|h| u32::from_str_radix(h, 16).ok())
    {
        Some(h) => h,
        None => primase_foundations::hash::joaat(name.as_bytes()),
    }
}

/// The Enhanced name and legacy name of a stored texture parameter name hash.
pub fn texture_param(hash: u32) -> Option<(&'static str, &'static str)> {
    TEXTURE_PARAMS.iter().copied().find(|(n, _)| hash_of(n) == hash)
}

/// The Enhanced name and legacy name of a stored constant buffer parameter name hash (the first legacy name where an
/// Enhanced name has two).
pub fn constant_param(hash: u32) -> Option<(&'static str, &'static str)> {
    CONSTANT_PARAMS.iter().copied().find(|(n, _)| hash_of(n) == hash)
}
