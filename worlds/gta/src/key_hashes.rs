//! SHA-1 digests of GTA V's archive key material, as published by the community archive tools.
//!
//! These are checksums for verifying key material the caller supplies; they are not keys and cannot decrypt
//! anything. No key, table or other decrypting material is part of this crate.

const fn nibble(c: u8) -> u8 {
    match c {
        b'0'..=b'9' => c - b'0',
        b'a'..=b'f' => c - b'a' + 10,
        _ => panic!("not a lowercase hex digit"),
    }
}

const fn hex(s: &str) -> [u8; 20] {
    let b = s.as_bytes();
    assert!(b.len() == 40);
    let mut out = [0u8; 20];
    let mut i = 0;
    while i < 20 {
        out[i] = nibble(b[2 * i]) << 4 | nibble(b[2 * i + 1]);
        i += 1;
    }
    out
}

