//! GIIV identity/layout census against an independent SoulsFormats reading of Ashina.
mod common;
mod inputs;
use fromsoft_formats::{Game, Keys, dcx::Decoder, msb::MapLayout};
use primase_core::pass::{Pass, PassLog};
use primase_core::{Component, IrradianceVolume, TextureLayers, TextureShape, World};
use primase_fromsoft::{
    game::ParamKey,
    sekiro::{self, IrradianceRegion},
};
use sha2::{Digest, Sha256};

#[test]
fn all_authored_boxes_join_complete_source_volume_groups() -> Result<(), Box<dyn std::error::Error>> {
    let (Some(root), Some(keys), Some(dll)) = (
        inputs::install(inputs::Game::Sekiro),
        inputs::keys(inputs::Game::Sekiro),
        inputs::oodle(inputs::Tool::Oodle6),
    ) else {
        return Ok(());
    };
    let dll = common::oodle(dll)?;
    let decoder = Decoder {
        oodle: Some(&dll),
        max_output: 1 << 30,
    };
    let keys = Keys::from_folder(keys, Game::Sekiro, Game::Sekiro.param_key_sha256())?;
    let archive = common::install(root, Game::Sekiro, keys).open()?;
    let layout = MapLayout::read(&archive.read("/map/MapStudio/m11_01_00_00.msb.dcx", &decoder)?)?;
    let mut world = World::new();
    let report = sekiro::irradiance::read(&archive, &decoder, "m11_01_00_00", &layout, &mut world)?;
    // Independent source census: six packages, 116 complete coefficient groups each,
    // 107 authored boxes, nine additional groups without an authored box in this map.
    assert_eq!(
        (
            report.packages,
            report.textures,
            report.boxes,
            report.unplaced_groups
        ),
        (6, 2784, 642, 54)
    );
    assert!(
        world.verify_components().is_empty(),
        "{:?}",
        world.verify_components()
    );
    sekiro::passes::irradiance::LowerFromSoftIrradiance.run(&mut world, &mut PassLog::default())?;
    assert_eq!(world.iter::<IrradianceVolume>().count(), 642);
    assert!(
        world.verify_components().is_empty(),
        "{:?}",
        world.verify_components()
    );
    let (entity, source) = world
        .iter::<IrradianceRegion>()
        .find(|(_, r)| r.package == 3 && r.region.name.starts_with("Env_Box230_"))
        .expect("captured region");
    assert_eq!(
        (source.priority, source.fade_distance, source.diffuse_intensity),
        (20, 3., 1.)
    );
    // The game's seq665 object matrix, after reflecting world Z only. The box's
    // authored origin is its bottom: its centre is origin Y plus half height.
    assert_eq!(
        world
            .get::<primase_core::Transform>(entity)
            .expect("box transform")
            .cols,
        [
            [41.431087, 0., -23.92025],
            [0., 27.211, -0.],
            [-24.72, 0., -42.816296],
            [-163.121, -16.050001, -172.66],
        ]
    );
    let volume = world.get::<IrradianceVolume>(entity).expect("lowered region");
    // SHA256 of the compressed payload independently extracted from the game's TPF
    // through SoulsFormats, X/Y/Z/W order; no bytes generated by this reader.
    let expected = [
        "e9e6e05fca8cd4de1975c552141602f2d09e2d523214db11b9f9d93d149a6379",
        "dc5cd6ba7f2e066d111b1408b749c5c511e1eb7c9aa4f011ed88adb89fbe7945",
        "bfae6f7afce138a7e70ec377b4b3f73efb932dbbad5fe5a2d240242a754e5bde",
        "33afb75d4b3bb4e6f3bc006284f5bb863e83e84d37bb503538419a59bbecc5b7",
    ];
    for (texture, expected) in volume.coefficients.into_iter().zip(expected) {
        let data = world.get::<TextureLayers>(texture).expect("volume texture");
        assert_eq!(
            (data.width, data.height, data.shape),
            (28, 16, TextureShape::Volume { depth: 32 })
        );
        let mut hash = Sha256::new();
        for slice in &data.levels[0] {
            hash.update(slice);
        }
        let digest: String = hash.finalize().iter().map(|b| format!("{b:02x}")).collect();
        assert_eq!(digest, expected);
        data.verify(texture, &world)?;
    }
    let closure = world.closure([entity]);
    for texture in volume.coefficients {
        assert!(closure.contains(&texture));
    }
    // The two neighboring fallback producers from the same capture. One has no
    // package00: stored state names must not be mistaken for dense axis indices.
    for (area, packages, textures, boxes) in [("m11_00_00_00", 5, 1100, 275), ("m11_02_00_00", 6, 480, 120)] {
        let layout = MapLayout::read(&archive.read(&format!("/map/mapstudio/{area}.msb.dcx"), &decoder)?)?;
        let report = sekiro::irradiance::read(&archive, &decoder, area, &layout, &mut world)?;
        assert_eq!(
            (
                report.packages,
                report.textures,
                report.boxes,
                report.unplaced_groups
            ),
            (packages, textures, boxes, 0)
        );
    }
    let axis = world
        .iter::<primase_core::state::StateAxis>()
        .find(|(_, a)| a.key == "fromsoft.irradiance.m11_00_00_00")
        .expect("fallback package axis")
        .1;
    assert_eq!(axis.default, None);
    assert_eq!(axis.domain.parse("package-03"), Some(2));
    let mut log = PassLog::default();
    sekiro::passes::irradiance::LowerFromSoftIrradiance.run(&mut world, &mut log)?;
    assert_eq!(world.iter::<IrradianceVolume>().count(), 1031);
    assert_eq!(
        log.omitted["irradiance coefficient grids differ; common normal-offset grid is unresolved"],
        6
    );
    // Independently extracted neighboring DDS headers identify all six mixed-grid
    // groups. They remain complete source records, not resampled core volumes.
    let mut refused: Vec<_> = world
        .iter::<IrradianceRegion>()
        .filter(|(e, _)| !world.has::<IrradianceVolume>(*e))
        .map(|(_, r)| {
            (
                r.area.as_str(),
                r.package,
                r.region.name.split('_').nth(1).expect("box id"),
            )
        })
        .collect();
    refused.sort();
    assert_eq!(
        refused,
        vec![
            ("m11_00_00_00", 1, "Box300"),
            ("m11_00_00_00", 1, "Box307"),
            ("m11_00_00_00", 1, "Box323"),
            ("m11_00_00_00", 5, "Box250"),
            ("m11_00_00_00", 5, "Box300"),
            ("m11_00_00_00", 5, "Box307"),
        ]
    );
    assert!(
        world.verify_components().is_empty(),
        "{:?}",
        world.verify_components()
    );
    Ok(())
}
