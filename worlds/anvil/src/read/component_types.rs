/// Whether `kind` is the type of a component class.
pub fn is_component_type(kind: u32) -> bool {
    COMPONENT_TYPES.binary_search_by_key(&kind, |&(id, _)| id).is_ok()
}

/// The class name of the component type `kind`.
pub fn component_name(kind: u32) -> Option<&'static str> {
    COMPONENT_TYPES
        .binary_search_by_key(&kind, |&(id, _)| id)
        .ok()
        .and_then(|i| COMPONENT_TYPES.get(i))
        .map(|&(_, name)| name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_and_names_the_known_components() {
        assert!(COMPONENT_TYPES.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(component_name(crate::read::entity::VISUAL), Some("Visual"));
        assert_eq!(
            component_name(crate::read::entity::RIGID_BODY),
            Some("RigidBodyComponent")
        );
        assert!(!is_component_type(crate::read::entity::BOUNDING_VOLUME));
    }
}
